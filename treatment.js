/* Dentara — client-side renderer for treatment.html?t=<slug>
   (Static, indexable pages are generated by build.js into /treatments/.) */
(function () {
  "use strict";
  var D = window.DentaraData, C = window.DENTARA_CONFIG || {};
  var slug = new URLSearchParams(location.search).get("t");
  var t = D.bySlug[slug];

  // Unknown or missing slug → send visitors to the treatment list instead of showing the wrong page
  if (!t) { location.replace("index.html#treatments"); return; }

  var waText = "Hello Dentara, I'd like to enquire about " + t.name + ".";
  var waUrl = "https://wa.me/" + (C.waNumber || "") + "?text=" + encodeURIComponent(waText);
  document.body.setAttribute("data-wa", waText);   // picked up by common.js
  document.title = t.name + " — Dentara Dental Studio";
  var md = document.querySelector('meta[name="description"]');
  if (md) md.content = t.name + " at Dentara Dental Studio. " + t.tagline;

  document.getElementById("app").innerHTML = D.render(t, {
    home: "", waUrl: waUrl,
    cardHref: function (s) { return "treatment.html?t=" + s; }
  });
})();
